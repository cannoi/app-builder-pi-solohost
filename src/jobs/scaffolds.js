import fs from 'node:fs/promises';
import path from 'node:path';

/**
 * Deterministic SoloHost-friendly boilerplate (Release B4). No AI involved: when the model forgets these
 * files they are generated locally, so a "missing Dockerfile" never costs an AI call and never ends in a
 * "done" project that cannot build. Existing files are never overwritten.
 */

async function readPkg(sourceDir) {
  try { return JSON.parse(await fs.readFile(path.join(sourceDir, 'package.json'), 'utf8')); } catch { return null; }
}

/** Entry file for CMD: `npm start` script ("node x.js"), then package.json "main", then server.js. */
export function detectEntry(pkg) {
  const start = String(pkg?.scripts?.start || '');
  const m = /\bnode\s+(?:--[\w-]+(?:=\S+)?\s+)*([^\s&|;]+\.(?:c|m)?js)\b/.exec(start);
  if (m) return m[1].replace(/^\.\//, '');
  if (pkg?.main && /\.(?:c|m)?js$/.test(pkg.main)) return String(pkg.main).replace(/^\.\//, '');
  return 'server.js';
}

function dockerfile(entry) {
  return `FROM node:22-alpine
WORKDIR /app
ENV NODE_ENV=production
COPY package*.json ./
RUN npm install --omit=dev --ignore-scripts --no-audit --no-fund || true
COPY . .
USER node
ENV PORT=8080
EXPOSE 8080
HEALTHCHECK --interval=20s --timeout=5s --start-period=15s --retries=3 \\
  CMD node -e "fetch('http://127.0.0.1:'+(process.env.PORT||8080)+'/health').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"
CMD ["node","${entry}"]
`;
}

const DOCKERIGNORE = `node_modules
npm-debug.log
.git
.env
data
projects
workspace
`;

const GITIGNORE = `node_modules/
data/
*.log
.env
.DS_Store
`;

const ENV_EXAMPLE = `PORT=8080
`;

function smokeTest(pkg, entry) {
  const esm = pkg?.type === 'module';
  const head = esm
    ? `import test from 'node:test';\nimport assert from 'node:assert/strict';\nimport fs from 'node:fs';\n`
    : `const test = require('node:test');\nconst assert = require('node:assert/strict');\nconst fs = require('node:fs');\n`;
  return `${head}
// Generated by App Builder: a dependency-free smoke test (the app itself is checked live by Run/Preview).
test('project files are present', () => {
  assert.ok(fs.existsSync('package.json'), 'package.json');
  assert.ok(fs.existsSync(${JSON.stringify(entry)}), ${JSON.stringify(entry)});
});
`;
}

function readme(pkg) {
  const name = String(pkg?.name || 'My SoloHost App');
  const desc = String(pkg?.description || 'A small web app for Pi Network SoloHost.');
  return `# ${name}\n\n${desc}\n\n## Run\n\n\`\`\`\nnpm install\nnpm start\n\`\`\`\n\nOpen http://127.0.0.1:8080\n`;
}

/**
 * Ensure deterministic boilerplate exists. Returns the list of files that were written.
 */
export async function ensureBoilerplate(sourceDir) {
  const written = [];
  const pkg = await readPkg(sourceDir);
  const entry = detectEntry(pkg);
  async function put(rel, body) {
    const abs = path.join(sourceDir, rel);
    try {
      await fs.access(abs);
      return;
    } catch { /* missing */ }
    await fs.mkdir(path.dirname(abs), { recursive: true });
    await fs.writeFile(abs, body, 'utf8');
    written.push(rel);
  }
  await put('Dockerfile', dockerfile(entry));
  await put('.dockerignore', DOCKERIGNORE);
  await put('.gitignore', GITIGNORE);
  await put('.env.example', ENV_EXAMPLE);
  await put('README.md', readme(pkg));
  // Only add a smoke test when the project has none and `npm test` would otherwise fail on a missing file.
  const testScript = String(pkg?.scripts?.test || '');
  const referencesTestJs = !pkg || !testScript || /\btest\.js\b/.test(testScript);
  if (referencesTestJs) await put('test.js', smokeTest(pkg, entry));
  // `npm test` must exist, otherwise the verification step itself fails ("Missing script: test").
  if (pkg && !testScript) {
    try {
      pkg.scripts = { ...(pkg.scripts || {}), test: 'node test.js' };
      await fs.writeFile(path.join(sourceDir, 'package.json'), JSON.stringify(pkg, null, 2) + '\n', 'utf8');
      written.push('package.json (scripts.test)');
    } catch { /* leave package.json untouched */ }
  }
  return written;
}

export default { ensureBoilerplate, detectEntry };
