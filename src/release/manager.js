import { writeSafeFile } from '../utils/fsx.js';
import { uuid, semverBump } from '../utils/ids.js';
import { writeSoloHostPackage } from './solohost.js';
import { lintPackage } from './solohost-lint.js';
import { validateRemote } from './solohost-api.js';
import { formatSoloHostErrors } from './solohost-errors.js';
import fs from 'node:fs/promises';
import path from 'node:path';

export { formatSoloHostErrors } from './solohost-errors.js';

export class ReleaseManager {
  constructor({ cfg, db, log }) {
    this.cfg = cfg;
    this.db = db;
    this.log = log;
  }

  list(projectId) {
    return this.db.all('SELECT * FROM releases WHERE project_id = ? ORDER BY created_at DESC', projectId);
  }

  async prepareNotes(project, sourceDir, quality) {
    const version = project.version || '0.1.0';
    const notes = `# ${project.name} ${version}

Generated by App Builder — Pi SoloHost.

## What it does
${project.idea || project.name}

## Quality
${quality ? JSON.stringify(quality, null, 2) : 'See project checks.'}

## Install
Read INSTALL.md in the project folder.
`;
    await writeSafeFile(sourceDir, 'RELEASE_NOTES.md', notes);
    await writeSafeFile(sourceDir, 'CHANGELOG.md', `## ${version}\n\n- Initial release generated from your idea.\n`);
    return { version, notes };
  }

  /**
   * Validate SoloHost package: local lint (errors block) + remote validator.
   * @param {string} sourceDir
   * @param {{ acceptUnverified?: boolean }} opts
   */
  async validateSoloHost(sourceDir, opts = {}) {
    try {
      const compose = await fs.readFile(path.join(sourceDir, 'solohost', 'docker-compose.yml'), 'utf8');
      const config = await fs.readFile(path.join(sourceDir, 'solohost', 'config_options.yml'), 'utf8');

      const lint = lintPackage({ composeText: compose, configText: config, policy: opts.policy || null });
      if (lint.errors.length) {
        return {
          ok: false,
          errors: lint.errors.map((e) => e.rule + ': ' + (e.params?.var || e.params?.name || e.path || e.messageKey)),
          lint,
          mode: 'lint',
          authoritative: false,
        };
      }

      const remote = await validateRemote({ composeYaml: compose, configOptionsYaml: config });
      if (remote.status === 'ok') {
        return {
          ok: true,
          errors: [],
          warnings: lint.warnings,
          lint,
          mode: 'remote',
          authoritative: true,
        };
      }
      if (remote.status === 'fail') {
        return {
          ok: false,
          errors: (remote.errors || []).map((e) => e.message || e.rule),
          lint,
          remote,
          mode: 'remote-fail',
          authoritative: true,
        };
      }
      // unreachable
      if (opts.acceptUnverified === true) {
        return {
          ok: true,
          errors: [],
          warnings: [
            ...(lint.warnings || []),
            { rule: 'UNREACHABLE', message: 'SoloHost validator unreachable; accepted with acceptUnverified.' },
          ],
          lint,
          remote,
          mode: 'local-unverified',
          authoritative: false,
        };
      }
      return {
        ok: false,
        errors: ['SoloHost validator unreachable. Retry later or confirm acceptUnverified.'],
        code: 'UNREACHABLE',
        lint,
        remote,
        mode: 'unreachable',
        authoritative: false,
      };
    } catch (err) {
      return { ok: false, errors: [String(err.message || err)], mode: 'error' };
    }
  }

  async prepareSoloHost(project, sourceDir, image, description = '', extra = {}) {
    const { stableHostPort } = await import('./solohost-port.js');
    const path = await import('node:path');
    const metaDir = extra.metaDir || path.join(sourceDir, '..', 'metadata');
    const hostPort = await stableHostPort({ ...project, _metaDir: metaDir }, extra.hostPort, sourceDir);
    return writeSoloHostPackage({
      project,
      sourceDir,
      image,
      hostPort,
      description,
      fieldPolicy: extra.fieldPolicy || null,
    });
  }

  record(project, { version, notes, githubUrl, status = 'created' }) {
    const id = uuid();
    this.db.run(
      `INSERT INTO releases(id,project_id,version,notes,github_url,status,created_at)
       VALUES(?,?,?,?,?,?,?)`,
      id, project.id, version, notes, githubUrl || null, status, new Date().toISOString(),
    );
    return this.db.get('SELECT * FROM releases WHERE id = ?', id);
  }

  nextVersion(project, kind = 'patch') {
    return semverBump(project.version || '0.1.0', kind);
  }
}
